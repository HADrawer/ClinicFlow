export function I18nProvider({children}:{children:React.ReactNode}){
  const [locale,setLocaleState]=useState<Locale>("en");
  useLayoutEffect(()=>{const saved=window.localStorage.getItem("clinicflow_locale");const next=saved==="ar"?"ar":"en";setLocaleState(next);applyDocumentLocale(next)},[]);
  const setLocale=useCallback((next:Locale)=>{window.localStorage.setItem("clinicflow_locale",next);applyDocumentLocale(next);setLocaleState(next)},[]);
  const toggleLocale=useCallback(()=>setLocale(locale==="en"?"ar":"en"),[locale,setLocale]);
  const t=useCallback((key:string,values?:Values)=>translate(key,locale,values),[locale]);
  const label=useCallback((value:string)=>{const key=labelKey(value);return key?t(key):translateEnglish(value,locale)},[locale,t]);
  useEffect(()=>{
    const translateTree=(root:Node)=>{
      const translateTextNode=(node:Node)=>{
        if(node.parentElement?.closest("script,style,[data-no-translate]"))return;
        const current=node.textContent||"";
        if(locale==="ar"&&!originalText.has(node))originalText.set(node,current);
        let source=originalText.get(node)||current;
        if(locale==="ar"&&current!==source&&current!==translateEnglish(source,"ar")){originalText.set(node,current);source=current}
        const next=locale==="en"?source:translateEnglish(source,locale);
        if(next!==node.textContent)node.textContent=next;
      };
      if(root.nodeType===Node.TEXT_NODE)translateTextNode(root);
      const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
      let node:Node|null;
      while((node=walker.nextNode())){
        translateTextNode(node);
      }
      if(root instanceof Element){
        for(const element of [root,...Array.from(root.querySelectorAll("[placeholder],[aria-label],[title]"))]){
          for(const attr of ["placeholder","aria-label","title"]){const current=element.getAttribute(attr);if(!current)continue;let originals=originalAttributes.get(element);if(!originals){originals=new Map();originalAttributes.set(element,originals)}if(locale==="ar"&&!originals.has(attr))originals.set(attr,current);const source=originals.get(attr)||current;const next=locale==="en"?source:translateEnglish(source,locale);if(next!==current)element.setAttribute(attr,next)}
        }
      }
    };
    translateTree(document.body);
    const observer=new MutationObserver(records=>records.forEach(record=>{if(record.type==="characterData")translateTree(record.target);record.addedNodes.forEach(translateTree)}));
    observer.observe(document.body,{childList:true,characterData:true,subtree:true});
    return()=>observer.disconnect();
  },[locale]);
  const value=useMemo(()=>({locale,isRtl:locale==="ar",t,label,setLocale,toggleLocale}),[locale,t,label,setLocale,toggleLocale]);
  return <Context.Provider value={value}><Fragment key={locale}>{children}</Fragment></Context.Provider>;
}

